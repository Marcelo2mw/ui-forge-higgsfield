/** Textos da interface no idioma escolhido nas configurações. */
export function useT(): Dict {
  const lang = useApp((s) => s.settings?.uiLang ?? "pt-BR");
  return dict(lang);
}

export function useUiLang(): Lang {
  return useApp((s) => s.settings?.uiLang ?? "pt-BR");
}
